def seed_all_sources():
    db = SessionLocal()
    try:
        print(f"[SOURCES SEED] Starting sync for {len(ALL_INDIAN_SOURCES)} Indian publications...")
        added_count = 0
        updated_count = 0

        for src_data in ALL_INDIAN_SOURCES:
            existing = db.query(NewsSource).filter(NewsSource.slug == src_data["slug"]).first()
            if not existing:
                # Also check by publisher name
                existing = db.query(NewsSource).filter(NewsSource.publisher_name == src_data["publisher_name"]).first()

            if not existing:
                src = NewsSource(
                    publisher_name=src_data["publisher_name"],
                    slug=src_data["slug"],
                    official_website_url=src_data["official_website_url"],
                    language=src_data["language"],
                    country=src_data["country"],
                    coverage_categories=src_data["coverage_categories"],
                    source_type=src_data["source_type"],
                    rss_feed_url=src_data["rss_feed_url"],
                    permission_status=src_data["permission_status"],
                    content_usage_policy=src_data["content_usage_policy"],
                    collection_frequency=src_data["collection_frequency"],
                    enabled=src_data["enabled"],
                    credibility_score=src_data["credibility_score"]
                )
                db.add(src)
                db.flush()

                is_gov = src_data["source_type"] == "government"
                perm = SourcePermission(
                    source_id=src.id,
                    can_collect_headlines=True,
                    can_collect_descriptions=True,
                    can_create_original_summaries=True,
                    can_access_full_text=is_gov,
                    can_reuse_images=is_gov,
                    can_commercially_redistribute=False,
                    can_display_attribution=True,
                    notes=f"Configured for {src_data['publisher_name']} per Section 4 policy."
                )
                db.add(perm)
                added_count += 1
                print(f"  + Added: {src_data['publisher_name']} [{src_data['source_type']}]")
            else:
                # Update details if needed
                existing.official_website_url = src_data["official_website_url"]
                existing.language = src_data["language"]
                existing.coverage_categories = src_data["coverage_categories"]
                existing.source_type = src_data["source_type"]
                if src_data["rss_feed_url"]:
                    existing.rss_feed_url = src_data["rss_feed_url"]
                    existing.permission_status = "VERIFIED"
                    existing.enabled = True
                updated_count += 1

        db.commit()

        # Audit log
        audit = AuditLog(
            action_type="SOURCES_SYNCHRONIZED",
            target_type="NewsSource",
            summary=f"Synchronized full directory of {len(ALL_INDIAN_SOURCES)} Indian publications (Added: {added_count}, Updated: {updated_count})",
            details={"total_sources": len(ALL_INDIAN_SOURCES), "added": added_count, "updated": updated_count},
            performed_by="SOURCE_MANAGER"
        )
        db.add(audit)
        db.commit()

        total_in_db = db.query(NewsSource).count()
        enabled_in_db = db.query(NewsSource).filter(NewsSource.enabled == True).count()
        print(f"[SOURCES SEED] Completed! Total Sources in DB: {total_in_db} ({enabled_in_db} active feeds).")

    except Exception as e:
        db.rollback()
        print(f"[SOURCES SEED] Error: {e}")
        raise
    finally:
        db.close()

if __name__ == "__main__":
    seed_all_sources()
